def test_missing_condition_append_basic():
    """Tests that append_condition_to_answer appends condition verbatim and preserves citation block."""
    raw_answer = (
        "The late fee rate on overdue invoices is 2.0% per month (or 24% per annum pro-rata) on the outstanding principal.\n\n"
        "[invoice_terms_policy.pdf, p.1, §4.2 Overdue Invoices and Late Fee Structure]"
    )
    condition_sentence = "Interest charges will only apply if the delay is solely attributable to internal processing and not vendor billing errors."
    chunk = {
        "source_file": "invoice_terms_policy.pdf",
        "page": 1,
        "section": "4.2 Overdue Invoices and Late Fee Structure"
    }

    result = append_condition_to_answer(raw_answer, condition_sentence, chunk)
    assert condition_sentence in result
    assert "[invoice_terms_policy.pdf, p.1, §4.2 Overdue Invoices and Late Fee Structure]" in result
    assert result.index(condition_sentence) < result.index("[invoice_terms_policy.pdf")
    assert "2.0% per month" in result

def test_missing_condition_append_inline_citation():
    """Tests that append_condition_to_answer works with inline citations."""
    raw_answer = "The rate is 2.0% [invoice_terms_policy.pdf, p.1, §4.2]."
    cond = "Interest charges will only apply if the delay is solely attributable to internal processing."
    result = append_condition_to_answer(raw_answer, cond)
    assert cond in result
    assert result.endswith("[invoice_terms_policy.pdf, p.1, §4.2].") or "[invoice_terms_policy.pdf, p.1, §4.2]" in result

def test_missing_condition_append_no_duplicate():
    """Tests that append_condition_to_answer avoids duplicate appending when words are already present."""
    cond = "Interest charges will only apply if the delay is solely attributable to internal processing and not vendor billing errors."
    answer_with_cond = f"The rate is 2.0%. {cond}\n\n[invoice_terms_policy.pdf, p.1, §4.2]"
    result = append_condition_to_answer(answer_with_cond, cond)
    assert result == answer_with_cond

def test_g02_non_refusal_preservation():
    """Tests that gap answers stating policy does not specify a cap are not converted to refusals."""
    ans = "The policy does not specify a maximum cap on the late fee."
    ans_lower = ans.lower()
    is_gap_answer = any(phrase in ans_lower for phrase in ["not specif", "does not mention", "doesn't mention", "no mention", "not state", "not address", "no cap", "no grace"])
    assert is_gap_answer is True
    # Verify that 'couldn't find' is not present
    assert "couldn't find" not in ans_lower

def test_phase_action_false_alarm_case():
    """Tests that a correct multi-phase sentence does not trigger a false-alarm PHASE_ACTION flag."""
    chunks = [{
        "source_file": "invoice_terms_policy.pdf",
        "page": 1,
        "section": "4.3 Overdue Escalation Workflow",
        "content": (
            "4.3 Overdue Escalation Workflow\n"
            "Phase 1 (Day 1 to 14 Overdue): Automated reminder notification generated by ERP and dispatched to vendor relationship manager.\n"
            "Phase 2 (Day 15 Overdue): Mandatory escalation meeting between Finance Controller and Vendor Account Lead. Accounts Payable freezes new purchase order issuance to the vendor.\n"
            "Phase 3 (Day 30+ Overdue): Formal dispute review and legal notification protocol activated."
        )
    }]
    # Correct assertion associating Phase 1 with notifications and Phase 2 with freezing POs
    correct_answer = (
        "Phase 1 (Day 1 to 14 Overdue) sends automated ERP reminder notifications to the vendor relationship manager, "
        "and at Phase 2 (Day 15 Overdue) Accounts Payable freezes new purchase order issuance [invoice_terms_policy.pdf, p.1, §4.3]."
    )
    flags = check_phase_action_consistency(correct_answer, chunks)
    assert flags == [], f"Expected no flags for correct answer, got: {flags}"

def test_phase_action_true_positive_detection():
    """Tests that an incorrect answer claiming Phase 1 freezes orders is flagged."""
    chunks = [{
        "source_file": "invoice_terms_policy.pdf",
        "page": 1,
        "section": "4.3 Overdue Escalation Workflow",
        "content": (
            "4.3 Overdue Escalation Workflow\n"
            "Phase 1 (Day 1 to 14 Overdue): Automated reminder notification generated by ERP and dispatched to vendor relationship manager.\n"
            "Phase 2 (Day 15 Overdue): Mandatory escalation meeting between Finance Controller and Vendor Account Lead. Accounts Payable freezes new purchase order issuance to the vendor.\n"
            "Phase 3 (Day 30+ Overdue): Formal dispute review and legal notification protocol activated."
        )
    }]
    wrong_answer = (
        "Phase 1 (Day 1 to 14 Overdue) Accounts Payable freezes new purchase order issuance to the vendor [invoice_terms_policy.pdf, p.1, §4.3]."
    )
    flags = check_phase_action_consistency(wrong_answer, chunks)
    assert any("PHASE_ACTION" in f for f in flags)


def test_data_claim_guard_m03_variants():
    """
    Tests DATA CLAIM GUARD with M03 tool result:
    - '4 unpaid invoices' must be corrected to 7
    - '3 invoices are overdue' must be corrected to 4
    - 'total ₹24,98,174.47' must be corrected to ₹29,78,174.47
    - '7 unpaid invoices, 4 overdue and 3 pending' must pass unchanged
    """
    from app.utils.deterministic_guard import verify_and_guard_data_claims
    tool_res = [{
        "found": True,
        "count": 7,
        "total_amount": 2978174.47,
        "status_breakdown": {"Overdue": 4, "Pending": 3},
        "invoices": [
            {"invoice_id": "INV-2024-055", "amount_inr": 800150.57, "status": "Overdue"},
            {"invoice_id": "INV-2024-043", "amount_inr": 594743.01, "status": "Overdue"},
            {"invoice_id": "INV-2024-040", "amount_inr": 540212.31, "status": "Overdue"},
            {"invoice_id": "INV-2024-083", "amount_inr": 480000.0, "status": "Pending"},
            {"invoice_id": "INV-2024-030", "amount_inr": 282313.45, "status": "Pending"},
            {"invoice_id": "INV-2024-017", "amount_inr": 224186.59, "status": "Pending"},
            {"invoice_id": "INV-2024-019", "amount_inr": 56568.54, "status": "Overdue"},
        ]
    }]

    # Variant 1: wrong unpaid count ('4 unpaid invoices')
    ans1 = "Vendor ABC Corp has customized Net 45 terms. There are 4 unpaid invoices from Vendor ABC Corp."
    res1 = verify_and_guard_data_claims(ans1, tool_res)
    assert "There are 7 matching invoices" in res1
    assert "4 unpaid invoices" not in res1

    # Variant 2: wrong overdue count ('3 invoices are overdue')
    ans2 = "Vendor ABC Corp has customized Net 45 terms. 3 invoices are overdue."
    res2 = verify_and_guard_data_claims(ans2, tool_res)
    assert "There are 7 matching invoices" in res2
    assert "3 invoices are overdue" not in res2

    # Variant 3: wrong total ('total ₹24,98,174.47')
    ans3 = "Vendor ABC Corp has customized Net 45 terms. Total value of ₹24,98,174.47."
    res3 = verify_and_guard_data_claims(ans3, tool_res)
    assert "There are 7 matching invoices" in res3
    assert "24,98,174.47" not in res3
    assert "29,78,174.47" in res3

    # Variant 4: correct claims ('7 unpaid invoices, 4 overdue and 3 pending') must pass unchanged
    ans4 = "Vendor ABC Corp is granted customized Net 45 payment terms. There are 7 unpaid invoices, 4 overdue and 3 pending."
    res4 = verify_and_guard_data_claims(ans4, tool_res)
    assert res4 == ans4


def test_harness_i07_leak_fails():
    """
    Tests that a fake output whose visible late-fee sentence has a wrong amount
    but whose debug JSON contains the correct fee must FAIL I07.
    """
    import re, json
    from pathlib import Path
    from eval.run_eval import score, load_df

    qs_path = Path("eval/questions.json")
    qs = {q["id"]: q for q in json.loads(qs_path.read_text(encoding="utf-8"))}
    q_i07 = qs["I07"]
    df = load_df()

    fake_output = (
        "--- ANSWER ---\n"
        "The late fee owed on INV-2024-036 is ₹99,999.00.\n"
        "--- END ANSWER ---\n\n"
        "[DEBUG TOOL RESULTS]: [{\"found\": true, \"fee\": 96272.75, \"days\": 170}]\n"
        "[DEBUG METRICS] Backend: POSTGRES\n"
    )

    m = re.search(r"--- ANSWER ---\n(.*?)\n--- END ANSWER ---", fake_output, re.S)
    parsed_answer = m.group(1).strip() if m else ""
    r = {"answer": parsed_answer, "tools": ["calculate_late_fee"], "error": None}
    s = score(q_i07, r, df)

    assert not s["passed"], f"Expected I07 to FAIL with wrong visible amount, but passed! Fails: {s['fails']}"
    assert any("expected fee" in f for f in s["fails"])


