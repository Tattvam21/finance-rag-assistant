def test_invalid_range_lower_bound_exceeds_upper_rejected():
    # An inverted range clause where lower bound > upper bound must be rejected
    from app.utils.numeric_grounding import PolicyRangeRule
    with pytest.raises(ValueError, match="Lower bound .* cannot be greater than upper bound"):
        PolicyRangeRule(
            raw_clause="between ₹10,00,000 and ₹2,00,000",
            sentence="Corrupted clause between ₹10,00,000 and ₹2,00,000",
            min_val=1000000.0,
            max_val=200000.0
        )

def test_overdue_days_boundary_ranges():
    """
    Task 3: Boundary tests for days 0, 1, 14, 15, 16, 20, 29, 30, 31 against §4.3 escalation phases.
    Emits verified facts strictly according to retrieved chunk text without invented clauses.
    """
    # Day 0: Not overdue
    b0, _ = build_verified_numeric_facts("What escalation applies if 0 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "0 days overdue: Not overdue; no overdue escalation phase applies." in b0

    # Day 1: Phase 1 boundary start
    b1, _ = build_verified_numeric_facts("What escalation applies for 1 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "1 days overdue falls in 'Day 1 to 14 Overdue' (Phase 1)" in b1

    # Day 14: Phase 1 boundary end
    b14, _ = build_verified_numeric_facts("What escalation applies for 14 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "14 days overdue falls in 'Day 1 to 14 Overdue' (Phase 1)" in b14

    # Day 15: Phase 2 (strictly Day 15 Overdue)
    b15, _ = build_verified_numeric_facts("What happens when an invoice reaches day 15 overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "15 days overdue falls in 'Day 15 Overdue' (Phase 2)" in b15

    # Day 16: Gap days 16-29 start
    b16, _ = build_verified_numeric_facts("What escalation applies for 16 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "Phase 2 was triggered on Day 15; Phase 3 starts at Day 30+; the policy does not define days 16-29 explicitly." in b16

    # Day 20: Gap days 16-29 midpoint
    b20, _ = build_verified_numeric_facts("What escalation applies for 20 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "Phase 2 was triggered on Day 15; Phase 3 starts at Day 30+; the policy does not define days 16-29 explicitly." in b20

    # Day 29: Gap days 16-29 end
    b29, _ = build_verified_numeric_facts("What escalation applies for 29 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "Phase 2 was triggered on Day 15; Phase 3 starts at Day 30+; the policy does not define days 16-29 explicitly." in b29

    # Day 30: Phase 3 boundary start
    b30, _ = build_verified_numeric_facts("What escalation applies for 30 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "30 days overdue falls in 'Day 30+ Overdue' (Phase 3)" in b30

    # Day 31: Phase 3 continuation
    b31, _ = build_verified_numeric_facts("What escalation applies for 31 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "31 days overdue falls in 'Day 30+ Overdue' (Phase 3)" in b31

    # Day 97: Realistic overdue invoice (e.g. INV-2024-048)
    b97, _ = build_verified_numeric_facts("What escalation applies for 97 days overdue?", [SAMPLE_ESCALATION_CHUNK])
    assert "97 days overdue falls in 'Day 30+ Overdue' (Phase 3)" in b97

