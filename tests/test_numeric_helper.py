def test_amount_parsing():
    assert parse_inr_amount("₹30,000") == 30000.0
    assert parse_inr_amount("30000") == 30000.0
    assert parse_inr_amount("1.5 lakh") == 150000.0
    assert parse_inr_amount("2 crore") == 20000000.0
    assert parse_inr_amount("₹7,13,742.58") == 713742.58
    assert parse_inr_amount("5,001") == 5001.0

